import { expect, test } from '@playwright/test';

const fixtureOrigin = `http://127.0.0.1:${process.env.RUSTX_E2E_FIXTURE_PORT ?? 5174}`;
for (const width of [1440, 390]) test(`workflow catalog counts three children before inspection and after reload at ${width}px`, async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(`${fixtureOrigin}/test/fixtures/agent.html?mode=workflow-catalog`);
  await expect(page).toHaveTitle('Session A — rustX');
  await expect(page).toHaveURL(/agent\.html\?mode=workflow-catalog$/);
  const list = page.getByRole('button', { name: 'Subagents', exact: true });
  const tree = page.getByRole('tree', { name: 'Subagents', exact: true });
  await expect(list).toHaveText('3 subagents');
  expect(await page.evaluate(() => window.workflowCatalogFixture.statusReads())).toBe(0);
  const parent = await page.locator('#session-title').innerText();
  await list.press('ArrowDown');
  await expect(tree.getByRole('treeitem')).toHaveCount(3);
  await expect(page.getByText('Workflow · code_quality_gate · Read-only')).toHaveCount(3);
  await expect(tree.getByRole('treeitem', { name: 'explore completed' })).toBeFocused();
  const screenshot = testInfo.outputPath(`workflow-catalog-${width}.png`);
  await page.screenshot({ path: screenshot }); await testInfo.attach('complete unvisited catalog', { path: screenshot, contentType: 'image/png' });
  await tree.getByRole('treeitem', { name: 'explore completed' }).press('Enter');
  const child = page.locator('[data-agent-id][data-view="chat"]:visible');
  await expect(child.getByRole('heading', { name: 'explore report' })).toBeVisible();
  await expect(child).toContainText('One-shot subagent record');
  await expect(child.getByRole('textbox')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Wait for activation', exact: true })).toHaveCount(0);
  // The switcher knows the other nodes even though none was previously opened.
  await list.click(); await tree.getByRole('treeitem', { name: 'review completed' }).click();
  await expect(child.getByRole('heading', { name: 'review report' })).toBeVisible();
  await page.getByRole('button', { name: 'Close Child view', exact: true }).click();
  await expect(list).toHaveText('3 subagents');
  await list.click(); await tree.getByRole('treeitem', { name: 'test completed' }).click();
  await expect(child.getByRole('heading', { name: 'test report' })).toBeVisible();
  await page.getByRole('button', { name: parent, exact: true }).click();
  await expect(list).toHaveText('3 subagents');
  await page.evaluate(() => window.workflowCatalogFixture.refresh()); await expect(list).toHaveText('3 subagents');
  await page.reload(); await expect(list).toHaveText('3 subagents');
  expect(await page.evaluate(() => window.workflowCatalogFixture.statusReads())).toBe(0);
  await list.click(); await expect(tree.getByRole('treeitem')).toHaveCount(3);
  await page.evaluate(() => localStorage.setItem('rustx-locale-v1', 'zh'));
  await page.reload();
  const localized = page.getByRole('button', { name: '子智能体', exact: true });
  await expect(localized).toHaveText('3 个子智能体');
  await localized.click();
  await expect(page.getByText('工作流 · code_quality_gate · 只读')).toHaveCount(3);
  const localizedScreenshot = testInfo.outputPath(`workflow-catalog-${width}-zh.png`);
  await page.screenshot({ path: localizedScreenshot });
  await testInfo.attach('localized unvisited catalog', { path: localizedScreenshot, contentType: 'image/png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.locator('vite-error-overlay')).toHaveCount(0); expect(errors).toEqual([]);
});

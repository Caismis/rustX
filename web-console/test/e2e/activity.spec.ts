test('header Jobs regroup on native settlement, clear ended output and remain reachable after scrolling', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()); });
  await page.goto(`${fixtureOrigin}/test/fixtures/activity.html`);
  await expect(page).toHaveTitle('rustX Jobs and Agents');
  await page.evaluate(() => window.activityFixture.jobs(3));
  const trigger = page.getByRole('button', { name: 'Background tasks', exact: true });
  await expect(trigger).toHaveText('3 background tasks running');
  await page.evaluate(() => window.scrollTo(0, 1200));
  await expect(trigger).toBeInViewport();
  await trigger.press('ArrowDown');
  const panel = page.getByRole('dialog', { name: 'Background tasks' });
  await expect(panel.getByRole('region')).toHaveCount(3);
  await page.evaluate(() => window.activityFixture.settle('job-0'));
  await expect(trigger).toHaveText('2 background tasks running');
  await expect(panel.getByRole('region', { name: 'Job Task 1' })).toBeHidden();
  await panel.getByRole('button', { name: 'Ended 1', exact: true }).click();
  await panel.getByRole('region', { name: 'Job Task 1' }).getByRole('button', { expanded: false }).click();
  await expect(panel.getByText('Final output job-0')).toBeVisible();
  await panel.screenshot({ path: '/tmp/rustx-background-jobs-panel.png' });
  await page.screenshot({ path: '/tmp/rustx-background-jobs-desktop.png' });
  await panel.press('Escape');
  await expect(trigger).toBeFocused();
  await trigger.click();
  await panel.getByRole('button', { name: 'Clear ended tasks' }).click();
  await expect(panel.getByRole('button', { name: 'Ended 1', exact: true })).toHaveCount(0);
  await page.evaluate(async () => { await window.activityFixture.settle('job-1'); await window.activityFixture.settle('job-2'); });
  await expect(trigger).toHaveText('2 background tasks');
  await expect(panel.getByRole('button', { name: 'Ended 2', exact: true })).toHaveAttribute('aria-expanded', 'true');
  await expect(panel.getByRole('region', { name: /^Job / })).toHaveCount(2);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(panel).toBeInViewport();
  expect(await panel.evaluate(element => { const r = element.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight; })).toBe(true);
  await page.screenshot({ path: '/tmp/rustx-background-jobs-mobile.png' });
  await panel.getByRole('button', { name: 'Clear ended tasks' }).click();
  await expect(trigger).toHaveCount(0);
  await expect(panel).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Session actions', exact: true })).toBeFocused();
  await page.reload();
  await expect(trigger).toHaveText('1 background tasks running');
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('Chat distinguishes background acceptance, recorded failure and command copying', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${fixtureOrigin}/test/fixtures/activity.html`);
  const launch = page.getByRole('region', { name: 'Background launch in chat' });
  await expect(launch).toContainText('Background task started');
  await launch.getByRole('button', { expanded: false }).click();
  await expect(launch.locator('[data-terminal]')).toHaveAttribute('data-background', '');
  await expect(launch.locator('[data-terminal] [data-state]')).toHaveCount(0);
  await expect(launch.getByRole('button', { name: 'Copy', exact: true })).toBeVisible();
  await expect(launch).not.toContainText('No output');
  const notice = page.getByRole('region', { name: 'Background completion in chat' });
  await expect(notice).toContainText('failed');
  await notice.getByRole('button', { expanded: false }).click();
  await expect(notice.getByText('Build output failed verification')).toBeVisible();
  await expect(notice).not.toContainText('Background execution');
  await page.screenshot({ path: '/tmp/rustx-background-chat.png' });
  expect(errors).toEqual([]);
});


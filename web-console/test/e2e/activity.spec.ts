test('header Jobs regroup on native settlement, clear ended output and remain reachable after scrolling', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()); });
  await page.goto(`${fixtureOrigin}/test/fixtures/activity.html`);
  await expect(page).toHaveTitle('rustX Jobs and Agents');
  await page.evaluate(() => window.activityFixture.jobs(3));
  const trigger = page.locator('[data-session-panel-toggle]');
  await expect(page.getByRole('button', { name: 'Session panel Background jobs running: 3', exact: true })).toBeVisible();
  await expect(page.locator('[data-jobs-running]')).toHaveCount(1);
  await page.locator('[data-fixture-transcript]').evaluate(element => element.scrollTo(0, 1200));
  await expect(trigger).toBeInViewport();
  await trigger.click();
  const panel = page.locator('[data-session-panel]');
  const section = panel.locator('[data-session-panel-section="background-jobs"]');
  await expect(section.getByRole('heading', { name: 'Background jobs', level: 2 })).toBeVisible();
  await expect(page.locator('[data-jobs-running]')).toHaveCount(0);
  await expect(section.getByRole('region')).toHaveCount(3);
  await page.evaluate(() => window.activityFixture.settle('job-0'));
  await expect(section.getByRole('region', { name: 'Job Task 1' })).toBeHidden();
  await section.getByRole('button', { name: 'Finished 1', exact: true }).click();
  await section.getByRole('region', { name: 'Job Task 1' }).getByRole('button', { expanded: false }).click();
  await expect(section.getByText('Final output job-0')).toBeVisible();
  await panel.screenshot({ path: '/tmp/rustx-background-jobs-panel.png' });
  await page.screenshot({ path: '/tmp/rustx-background-jobs-desktop.png' });
  await section.getByRole('region', { name: 'Job Task 1' }).getByRole('button', { expanded: true }).focus();
  await page.keyboard.press('Escape');
  await expect(trigger).toBeFocused();
  await trigger.click();
  await section.getByRole('button', { name: 'Clear finished jobs' }).click();
  await expect(section.getByRole('button', { name: 'Finished 1', exact: true })).toHaveCount(0);
  await page.evaluate(async () => { await window.activityFixture.settle('job-1'); await window.activityFixture.settle('job-2'); });
  await expect(section.getByRole('button', { name: 'Finished 2', exact: true })).toHaveAttribute('aria-expanded', 'true');
  await expect(section.getByRole('region', { name: /^Job / })).toHaveCount(2);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(panel).toBeInViewport();
  expect(await panel.evaluate(element => { const r = element.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight; })).toBe(true);
  await page.screenshot({ path: '/tmp/rustx-background-jobs-mobile.png' });
  await section.getByRole('button', { name: 'Clear finished jobs' }).click();
  await expect(trigger).toBeVisible();
  await expect(section).toBeHidden();
  await expect(page.locator('[data-jobs-running]')).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('button', { name: 'Session panel Background jobs running: 1', exact: true })).toBeVisible();
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  expect(errors).toEqual([]);
});


test('DSH task rows show command-copy output, exclusive expansion and two-press stopping', async ({ page, context }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()); });
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.addInitScript(() => localStorage.setItem('rustx-locale-v1', 'zh'));
  await page.goto(`${fixtureOrigin}/test/fixtures/activity.html?theme=dark`);
  await expect(page).toHaveTitle('rustX Jobs and Agents');
  expect(page.url()).toContain('/test/fixtures/activity.html');
  await page.getByRole('button', { name: '后台任务', exact: true }).click();
  const panel = page.getByRole('dialog', { name: '后台任务' });
  await expect(panel).toHaveAttribute('data-menu-material', 'translucent');
  await expect(panel).toContainText('printf authoritative-command');
  await panel.getByRole('button', { name: '展开 printf authoritative-command 的输出' }).click();
  await expect(panel.locator('[data-terminal]')).toHaveCount(1);
  await expect(panel.locator('[data-terminal] [data-state]')).toHaveCount(0);
  await expect(panel.getByRole('button', { name: /^(状态|等待作业|取消作业)$/ })).toHaveCount(0);
  await panel.getByRole('button', { name: '复制', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('printf authoritative-command');
  await panel.screenshot({ path: '/tmp/rustx-dsh-task-running.png' });
  await panel.getByRole('button', { name: '停止任务 printf authoritative-command' }).click();
  await expect(panel.getByRole('button', { name: '再次点击确认停止' })).toHaveText('确认停止');
  await expect(panel.getByRole('region', { name: '作业 Build' })).toHaveAttribute('data-job-state', 'running');
  await panel.getByRole('button', { name: '再次点击确认停止' }).click();
  await expect(panel.getByRole('button', { name: '已结束 1', exact: true })).toHaveAttribute('aria-expanded', 'true');
  await expect(panel).toContainText('Process settled');
  await expect(panel.getByRole('button', { name: /^停止任务 / })).toHaveCount(0);
  await panel.screenshot({ path: '/tmp/rustx-dsh-task-settled.png' });
  await page.evaluate(() => window.activityFixture.jobs(3));
  const rows = panel.getByRole('region');
  await rows.nth(0).getByRole('button', { expanded: false }).click();
  await rows.nth(1).getByRole('button', { expanded: false }).click();
  await expect(rows.nth(0).getByRole('button', { expanded: false })).toBeVisible();
  await expect(rows.nth(1).getByRole('button', { expanded: true })).toBeVisible();
  await expect(panel.locator('[data-terminal]')).toHaveCount(1);
  await page.setViewportSize({ width: 390, height: 844 });
  // Floating UI repositions after the resize observer runs. Observe the
  // settled geometry rather than racing that frame with an immediate read.
  await expect.poll(() => panel.evaluate(element => { const rect = element.getBoundingClientRect(); return rect.left >= 0 && rect.right <= innerWidth && rect.top >= 0 && rect.bottom <= innerHeight; })).toBe(true);
  await page.screenshot({ path: '/tmp/rustx-dsh-tasks-mobile.png' });
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  expect(errors).toEqual([]);
});

import { test, expect } from '@playwright/test';
const fixtureOrigin = `http://127.0.0.1:${process.env.RUSTX_E2E_FIXTURE_PORT ?? 5174}`;
for (const [width, locale, theme] of [[1440, 'en', 'light'], [390, 'zh', 'dark']] as const) test(`DSH attachment picker, page drop and rail ${width} ${locale} ${theme}`, async ({ page }) => {
  page.setDefaultTimeout(15000);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.addInitScript(({ locale, theme }) => { localStorage.setItem('rustx-locale-v1', locale); localStorage.setItem('rustx-appearance-v1', theme); }, { locale, theme });
  await page.goto(`${fixtureOrigin}/test/fixtures/agent.html?mode=composer`);
  await expect(page).toHaveTitle('Session A — rustX');
  const zh = locale === 'zh', message = page.getByRole('textbox', { name: zh ? '消息' : 'Message', exact: true });
  await expect(message).toBeEnabled();
  await message.fill('Keep this draft and caret.'); await message.evaluate((el: HTMLTextAreaElement) => el.setSelectionRange(5, 9));
  await page.getByRole('button', { name: zh ? '添加' : 'Add', exact: true }).click();
  const chooser = page.waitForEvent('filechooser'); await page.locator('#command-file').click();
  await (await chooser).setFiles({ name: 'report.md', mimeType: 'text/markdown', buffer: Buffer.from('# Report\n') });
  const ready = page.locator('[data-attachment-state=ready]');
  await expect(ready).toHaveCount(1); await expect(ready).toContainText('MD 9B');
  await expect(message).toHaveValue('Keep this draft and caret.');
  expect(await message.evaluate((el: HTMLTextAreaElement) => [el.selectionStart, el.selectionEnd])).toEqual([5, 9]);
  await expect(page.getByText(zh ? '已上传' : 'Uploaded', { exact: true })).toHaveCount(0);
  const data = await page.evaluateHandle(() => { const dt = new DataTransfer(); for (let index = 0; index < 12; index++) dt.items.add(new File([`note-${index}`], `note-${index}.txt`, { type: 'text/plain' })); return dt; });
  await page.locator('body').dispatchEvent('dragenter', { dataTransfer: data });
  await page.locator('body').dispatchEvent('dragover', { dataTransfer: data });
  const overlay = page.getByRole('status').filter({ hasText: zh ? '文件或图片拖动到此处即可添加' : 'Drag files or images here to add them' });
  await expect(overlay).toBeVisible();
  expect(await overlay.evaluate(el => { const r = el.getBoundingClientRect(); return [r.x, r.y, r.width, r.height, getComputedStyle(el).pointerEvents]; })).toEqual([0, 0, width, width === 390 ? 844 : 1000, 'none']);
  await page.screenshot({ path: `/tmp/rustx-upload-drop-${width}.png` });
  await page.locator('body').dispatchEvent('drop', { dataTransfer: data });
  await expect(overlay).toHaveCount(0); await expect(ready).toHaveCount(13);
  const group = page.getByRole('group', { name: zh ? '草稿附件' : 'Draft attachments' });
  await expect(group).toBeVisible();
  expect(await group.evaluate(el => el.scrollLeft > 0 && el.scrollWidth > el.clientWidth)).toBe(true);
  await page.screenshot({ path: `/tmp/rustx-upload-rail-${width}.png` });
  await page.getByRole('button', { name: zh ? '向左滚动附件' : 'Scroll attachments left' }).click();
  await group.evaluate(el => { el.scrollLeft = 0; });
  await expect(page.getByRole('button', { name: zh ? '向右滚动附件' : 'Scroll attachments right' })).toBeVisible();
  await group.hover(); await page.mouse.wheel(0, 80);
  await expect.poll(() => group.evaluate(el => el.scrollLeft)).toBeGreaterThan(0);
  // Invalid additions announce once and leave the entire existing draft intact.
  const invalid = await page.evaluateHandle(() => { const dt = new DataTransfer(); dt.items.add(new File(['invalid'], 'CON.txt')); return dt; });
  await page.locator('body').dispatchEvent('drop', { dataTransfer: invalid });
  await expect(page.getByRole('alert')).toContainText(zh ? '文件名不安全' : 'Unsafe filename');
  await expect(ready).toHaveCount(13);
  await group.evaluate(el => { el.scrollLeft = 0; });
  await ready.first().hover();
  await page.getByRole('button', { name: 'Remove report.md' }).or(page.getByRole('button', { name: '移除 report.md' })).click();
  await expect(ready).toHaveCount(12);
  await page.getByLabel(zh ? '附加文件' : 'Attach files', { exact: true }).setInputFiles({ name: 'pixel.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6pAAAAABJRU5ErkJggg==', 'base64') });
  await expect(ready).toHaveCount(13);
  const preview = page.getByRole('button', { name: zh ? '打开图片 pixel.png' : 'Open image pixel.png' });
  await preview.click(); await expect(page.getByRole('dialog', { name: 'pixel.png', exact: true })).toBeVisible();
  await page.keyboard.press('Escape'); await expect(page.getByRole('dialog', { name: 'pixel.png', exact: true })).toHaveCount(0);
  await expect(preview).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('DSH file card upload, retry and uncertain status preserve native evidence', async ({ page }) => {
  page.setDefaultTimeout(15000);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${fixtureOrigin}/test/fixtures/agent.html?mode=composer`);
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toBeEnabled();
  const input = page.getByLabel('Attach files');
  await page.evaluate(() => window.composerFixture.holdUploads());
  await input.setInputFiles({ name: 'retry.txt', mimeType: 'text/plain', buffer: Buffer.from('retry') });
  await expect(page.locator('[data-attachment-state=uploading]')).toHaveCount(1);
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled();
  await page.screenshot({ path: '/tmp/rustx-upload-pending.png' });
  await page.evaluate(() => window.composerFixture.settleUploads('failed'));
  await expect(page.getByRole('button', { name: /^Retry uploading / })).toContainText('retry.txt');
  await page.screenshot({ path: '/tmp/rustx-upload-failed.png' });
  await page.getByRole('button', { name: /^Retry uploading / }).click();
  await expect(page.locator('[data-attachment-state=ready]')).toHaveCount(1);
  expect(await page.evaluate(() => window.composerFixture.uploads())).toBe(2);
  await page.evaluate(() => window.composerFixture.holdUploads());
  await input.setInputFiles({ name: 'uncertain.txt', mimeType: 'text/plain', buffer: Buffer.from('uncertain') });
  await expect(page.locator('[data-attachment-state=uploading]')).toHaveCount(1);
  await page.evaluate(() => window.composerFixture.settleUploads('unresolved'));
  await expect(page.getByRole('button', { name: /^Check status for / })).toBeVisible();
  await expect(page.getByRole('button', { name: /^Retry uploading / })).toHaveCount(0);
  await page.getByRole('button', { name: /^Check status for / }).click();
  expect(await page.evaluate(() => window.composerFixture.uploads())).toBe(3);
  expect(errors).toEqual([]);
});

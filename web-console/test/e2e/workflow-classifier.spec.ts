import { test, expect } from '@playwright/test';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'yaml';
import { dataNodesDocument } from '../workflow-data-document';
import { viewId } from '../../src/app/workflows/ui/editor/selection';
import { startDogfood } from './dogfood-server';
import { connectRemote, openEmptySession, choose } from './shell-actions';
import { routeWorkspaceHost } from './workspace-host';

for (const width of [1440,390]) test.describe(`classifier panel ${width}`,()=>{
  test.use({viewport:{width,height:900},hasTouch:width===390});
  test('Dify class labels, variable prompts, sort and real file persistence',async({page})=>{
    page.setDefaultTimeout(15_000);
    const fixture=await startDogfood('web_console_dogfood'),errors:string[]=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('console',message=>{if(['error','warning'].includes(message.type()))errors.push(message.text());});
    try {
      await page.context().grantPermissions(['clipboard-read','clipboard-write']);
      const directory=join(fixture.workspaceA,'.agents/workflows');mkdirSync(directory,{recursive:true});
      const file=join(directory,'classify.yaml');writeFileSync(file,JSON.stringify(dataNodesDocument()));
      await page.addInitScript(dark=>localStorage.setItem('rustx-appearance-v1',dark?'dark':'light'),width===390);
      await routeWorkspaceHost(page,fixture);await page.goto('/');await connectRemote(page,fixture.endpoint,fixture.token);await openEmptySession(page,fixture,'Workspace A');
      await page.getByRole('navigation',{name:'Global panels'}).getByRole('button',{name:'Workflows',exact:true}).click();
      await page.getByRole('button',{name:'classify',exact:true}).click();
      await expect(page).toHaveTitle(/rustX$/);
      const card=page.locator(`.react-flow__node[data-id='${viewId([],'node','classify')}']`);
      await card.focus();await card.press('Enter');
      // The same source and layout, with product-owned Chinese wording.
      await page.getByRole('button',{name:'Settings',exact:true}).click();
      await choose(page.getByRole('dialog',{name:'Settings',exact:true}),'Language','中文');
      await page.getByRole('button',{name:'关闭设置',exact:true}).click();
      const panel=page.getByRole('complementary',{name:'检查器',exact:true});
      await expect(panel.getByText('视觉',{exact:true})).toHaveCount(0);
      await expect(panel.getByRole('textbox',{name:'Class ID',exact:true})).toHaveCount(0);
      await panel.getByRole('button',{name:'清除输入变量',exact:true}).click();
      await expect(panel.getByText('设置变量值',{exact:true})).toBeVisible();
      await panel.getByRole('button',{name:'选择变量',exact:true}).first().click();
      const picker=page.getByRole('dialog',{name:'选择变量',exact:true});
      await expect(picker.getByRole('button',{name:/^args \/ query /})).toBeEnabled();
      await expect(picker.getByRole('button',{name:/^args \/ priority /})).toBeEnabled();
      await expect(picker.getByRole('button',{name:/^args \/ memo /})).toHaveCount(0);
      await picker.getByRole('button',{name:/^args \/ priority /}).click();
      const rename=panel.getByRole('button',{name:'重命名CLASS 2',exact:true});
      if(width===390)await rename.tap();else await rename.dblclick();
      await panel.getByRole('textbox',{name:'分类标题',exact:true}).fill('售后支持');
      await panel.getByRole('textbox',{name:'分类标题',exact:true}).press('Enter');
      await expect(card.locator('[data-handleid="class_2"]')).toHaveCount(1);
      await expect(card).toContainText('售后支持');
      const second=panel.locator('[data-classifier-class="class_2"]');
      await second.getByRole('textbox',{name:'售后支持的主题内容',exact:true}).fill('处理请求：');
      await second.getByRole('button',{name:'插入变量',exact:true}).click();
      await picker.getByRole('button',{name:/^args \/ query /}).click();
      await expect(second).toContainText('query');
      await second.getByRole('button',{name:'展开',exact:true}).click();
      await expect(second.getByRole('button',{name:'收起',exact:true})).toHaveAttribute('aria-pressed','true');
      await expect(second.locator('[data-prompt-expanded]')).toHaveCSS('position','fixed');
      const expanded=(await second.locator('[data-prompt-expanded]').boundingBox())!,body=(await panel.locator('[data-workflow-inspector-body]').boundingBox())!;
      expect(Math.abs(expanded.height-body.height)).toBeLessThan(2);
      expect(Math.abs(expanded.y-body.y)).toBeLessThan(2);
      await second.getByRole('button',{name:'插入变量',exact:true}).click();
      await expect(picker).toBeVisible();
      await page.screenshot({path:`/tmp/rustx-classifier-expanded-${width}.png`});
      await picker.getByRole('textbox').press('Escape');
      await expect(second.locator('[data-prompt-expanded]')).toHaveCSS('position','fixed');
      await expect(second.getByRole('textbox',{name:'售后支持的主题内容',exact:true})).toBeFocused();
      await page.keyboard.press('Escape');
      await expect(second.locator('[data-prompt-expanded]')).toHaveCount(0);
      await second.getByRole('button',{name:'展开',exact:true}).click();
      await second.getByRole('button',{name:'收起',exact:true}).click();
      await second.getByRole('button',{name:'复制',exact:true}).click();
      await expect.poll(()=>page.evaluate(()=>navigator.clipboard.readText())).toContain('处理请求：');
      await panel.getByRole('button',{name:'移动售后支持',exact:true}).press('Alt+ArrowUp');
      await expect(panel.locator('[data-classifier-class]').first()).toHaveAttribute('data-classifier-class','class_2');
      await page.getByRole('button',{name:'撤销',exact:true}).click();
      await expect(panel.locator('[data-classifier-class]').first()).toHaveAttribute('data-classifier-class','class_1');
      await page.getByRole('button',{name:'重做',exact:true}).click();
      // Pointer sorting uses the same stable class IDs on mouse and real touch input.
      const handle=panel.getByRole('button',{name:'移动CLASS 1',exact:true});
      const from=(await handle.boundingBox())!,to=(await second.boundingBox())!;
      if(width===390){
        const cdp=await page.context().newCDPSession(page);
        await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:from.x+from.width/2,y:from.y+from.height/2}]});
        await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:to.x+to.width/2,y:to.y+20}]});
        await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await cdp.detach();
      }else{
        await page.mouse.move(from.x+from.width/2,from.y+from.height/2);await page.mouse.down();
        await page.mouse.move(to.x+to.width/2,to.y+20,{steps:8});await page.mouse.up();
      }
      await expect(panel.locator('[data-classifier-class]').first()).toHaveAttribute('data-classifier-class','class_1');
      await page.getByRole('button',{name:'撤销',exact:true}).click();
      await expect(panel.locator('[data-classifier-class]').first()).toHaveAttribute('data-classifier-class','class_2');
      await panel.getByRole('button',{name:'高级设置',exact:true}).click();
      await expect(panel.getByRole('textbox',{name:'指令',exact:true})).toHaveCount(0);
      await panel.getByRole('button',{name:'高级设置',exact:true}).click();
      await panel.getByRole('textbox',{name:'指令',exact:true}).fill('根据上下文判断：');
      const instruction=panel.getByRole('region',{name:'指令',exact:true});
      await instruction.getByRole('button',{name:'插入变量',exact:true}).click();
      await picker.getByRole('button',{name:/^args \/ query /}).click();
      await panel.getByRole('button',{name:'添加分类',exact:true}).click();
      const added=panel.getByRole('region',{name:'CLASS 3的主题内容',exact:true});
      await added.getByRole('textbox').fill('临时分类');
      await added.getByRole('button',{name:'删除分类 CLASS 3',exact:true}).click();
      await expect(added).toHaveCount(0);
      await panel.getByText('class_name',{exact:true}).scrollIntoViewIfNeeded();
      for(const name of ['class_name','class_label','usage'])await expect(panel.getByText(name,{exact:true})).toBeVisible();
      const save=page.getByRole('button',{name:'保存文件',exact:true});await save.click();await expect(save).toBeDisabled();
      const saved=parse(readFileSync(file,'utf8')),classifier=saved.block.nodes.classify;
      expect(classifier.input).toEqual({type:'reference',path:['args','priority']});
      expect(classifier.classes.map((item:any)=>item.id)).toEqual(['class_2','class_1']);
      expect(classifier.classes[0]).toMatchObject({label:'售后支持'});
      expect(classifier.classes[0].description).toContainEqual({type:'reference',path:['args','query']});
      expect(classifier.instruction).toContainEqual({type:'reference',path:['args','query']});
      expect(saved.block.edges.filter((edge:any)=>edge.from==='classify')).toEqual(dataNodesDocument().block.edges!.filter(edge=>edge.from==='classify'));
      await panel.getByRole('button',{name:'高级设置',exact:true}).scrollIntoViewIfNeeded();
      await panel.evaluate(element=>{const body=element.querySelector<HTMLElement>('[class*="inspectBody"]');if(body)body.scrollTop=0;});
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
      await expect(page.locator('vite-error-overlay')).toHaveCount(0);
      await expect(page.getByText(/已保存。运行时使用/)).toHaveCount(0);
      if(width===390)await panel.locator('[data-workflow-inspector-body]').evaluate(element=>{const section=element.querySelector<HTMLElement>('section[aria-label="分类"]');if(section)element.scrollTop+=section.getBoundingClientRect().top-element.getBoundingClientRect().top-8;});
      await page.screenshot({path:`/tmp/rustx-classifier-${width}.png`});
      await page.getByRole('button',{name:'返回工作流',exact:true}).first().click();
      await page.getByRole('button',{name:'classify',exact:true}).click();
      await card.focus();await card.press('Enter');
      await expect(panel.getByRole('button',{name:'重命名售后支持',exact:true})).toBeVisible();
      expect(errors).toEqual([]);
    } finally {await fixture.stop(false);}
  });
});

import { expect, test } from '@playwright/test';
import { appendFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { startDogfood } from './dogfood-server';
import { routeWorkspaceHost } from './workspace-host';

test('native MCP source authoring, Workspace shadowing, conflict repair and reset', async ({ page }) => {
  const fixture = await startDogfood(); const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await routeWorkspaceHost(page, fixture); await page.goto('/');
    await page.getByLabel('WebSocket endpoint').fill(`${fixture.endpoint}/`);
    await page.getByLabel('Transport token').fill(fixture.token);
    await page.getByRole('button', { name: 'Connect', exact: true }).click();
    await expect(page.locator('.status strong')).toHaveText('connected');
    await page.getByLabel('Choose Workspace').selectOption({ label: 'Workspace A' });
    await page.getByRole('button', { name: 'Create Session', exact: true }).click();
    await expect(page.locator('.session-toolbar small')).toContainText('attached');
    await page.getByRole('tab', { name: 'Settings', exact: true }).click();
    await page.getByRole('button', { name: 'Integrations', exact: true }).click();
    const integrations = page.getByRole('region', { name: 'Integrations', exact: true });
    await integrations.getByRole('button', { name: 'Add User MCP server' }).click();
    await integrations.getByLabel('Server identity').fill('local-fixture');
    await integrations.getByLabel('Command', { exact: true }).fill('python3');
    await integrations.getByRole('button', { name: 'Add Arguments', exact: true }).click();
    await integrations.getByLabel('Arguments 1', { exact: true }).fill(fileURLToPath(new URL('./web09-mcp.py', import.meta.url)));
    await integrations.getByRole('button', { name: 'Add Arguments', exact: true }).click();
    await integrations.getByLabel('Arguments 2', { exact: true }).fill(join(fixture.directory, 'mcp-started'));
    await integrations.getByRole('button', { name: 'Save MCP', exact: true }).click();
    await expect(integrations.getByText('Definition winner: User', { exact: true })).toBeVisible();
    await expect(integrations.getByLabel('Command', { exact: true })).toHaveCount(0);
    await integrations.getByLabel('Integration scope').selectOption('workspace');
    await integrations.getByRole('button', { name: 'Define Workspace · local-fixture' }).click();
    await integrations.getByLabel('Command', { exact: true }).fill('workspace-disabled-fixture');
    await integrations.getByRole('button', { name: 'Save MCP', exact: true }).click();
    await expect(integrations.getByText('Shadowed User definition — editable independently')).toBeVisible();
    await expect(integrations.getByLabel('Command', { exact: true })).toHaveCount(0);
    await integrations.getByLabel('Integration scope').selectOption('user');
    await integrations.getByRole('button', { name: 'Edit User · local-fixture' }).click();
    await integrations.getByLabel('Command', { exact: true }).fill('edited-shadowed-user');
    appendFileSync(fixture.settings, '\n# deterministic external CAS change\n');
    await integrations.getByRole('button', { name: 'Save MCP', exact: true }).click();
    await expect(page.getByRole('alert')).toContainText('Conflict');
    await expect(integrations.getByLabel('Command', { exact: true })).toHaveValue('edited-shadowed-user');
    await integrations.getByRole('button', { name: 'Save MCP', exact: true }).click();
    await expect(integrations.getByLabel('Command', { exact: true })).toHaveCount(0);
    await expect(integrations.getByText('Definition winner: Workspace', { exact: true })).toBeVisible();
    await integrations.getByLabel('Integration scope').selectOption('workspace');
    await integrations.getByRole('button', { name: 'Edit Workspace · local-fixture' }).click();
    await integrations.getByRole('button', { name: 'Delete authored MCP entry' }).click();
    await expect(integrations.getByText('Definition winner: User', { exact: true })).toBeVisible();
    // User policy survives loss of its sole authorized Workspace definition.
    await integrations.getByRole('button', { name: 'Add Workspace MCP server' }).click();
    await integrations.getByLabel('Server identity').fill('project-only');
    await integrations.getByLabel('Command', { exact: true }).fill('inert-project-only');
    await integrations.getByRole('button', { name: 'Save MCP', exact: true }).click();
    const policyCard = integrations.locator('article').filter({ has: page.getByRole('heading', { name: 'project-only', exact: true }) });
    await policyCard.getByText('User-owned Tool policy · project-only', { exact: true }).click();
    await policyCard.getByLabel('Approval · project-only').selectOption('always');
    await policyCard.getByRole('button', { name: 'Save User Tool policy', exact: true }).click();
    await expect(policyCard.getByText('User Tool policy: authored', { exact: true })).toBeVisible();
    // A second source write advances User authority while the policy draft stays pinned.
    await policyCard.getByLabel('Concurrency · project-only').selectOption('parallel');
    await integrations.getByLabel('Integration scope').selectOption('user');
    await integrations.getByLabel('goal', { exact: true }).click();
    await expect(integrations.getByLabel('goal', { exact: true })).toBeChecked();
    await expect(page.getByRole('status').filter({ hasText: 'Source committed' })).toBeVisible();
    await policyCard.getByRole('button', { name: 'Save User Tool policy', exact: true }).click();
    await expect(page.getByRole('alert')).toContainText('Conflict');
    await expect(policyCard.getByLabel('Concurrency · project-only')).toHaveValue('parallel');
    await policyCard.getByRole('button', { name: 'Retry User Tool policy', exact: true }).click();
    await expect(policyCard.getByRole('button', { name: 'Save User Tool policy', exact: true })).toBeVisible();
    fixture.revokeWorkspaceTrust();
    await page.getByRole('button', { name: 'Reload / discard draft', exact: true }).click();
    await expect(policyCard.getByText('Authorized MCP definition: absent', { exact: true })).toBeVisible();
    await expect(policyCard.getByText('User Tool policy: authored — dangling', { exact: true })).toBeVisible();
    await policyCard.screenshot({ path: 'test-results/web09-policy-dangling.png' });
    await policyCard.getByText('User-owned Tool policy · project-only', { exact: true }).click();
    await policyCard.getByRole('button', { name: 'Reset User Tool policy', exact: true }).click();
    await expect(policyCard).toHaveCount(0);
    await expect(integrations.getByText(/Native MCP validation failed/)).toHaveCount(0);
    await page.screenshot({ path: 'test-results/web09-integrations.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: 'test-results/web09-integrations-mobile.png', fullPage: true });
    expect(existsSync(join(fixture.directory, 'mcp-started'))).toBe(false);
    expect(errors).toEqual([]);
  } finally { const report = await fixture.stop(false); expect(report.requestCount).toBe(0); }
});

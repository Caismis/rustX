import { test, expect } from '@playwright/test';

const fixture = `http://127.0.0.1:${process.env.RUSTX_E2E_FIXTURE_PORT ?? 5174}/test/fixtures/startup.html?existing&models&subagents&subagent-observation-failure`;
for (const theme of ['dark', 'light'] as const) for (const width of [1440, 390]) test(`child read recovery retains evidence, editor and independent Stop ${theme} ${width}`, async ({ page }) => {
  const zh = width === 390;
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width, height: 900 });
  await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' });
  await page.addInitScript(locale => localStorage.setItem('rustx-locale-v1', locale), zh ? 'zh' : 'en');
  await page.goto(fixture);
  await page.waitForFunction(() => (window as any).startupFixture);
  await page.evaluate(() => { const f = (window as any).startupFixture; f.allow('session/summary'); f.allow('session/attach'); f.resumeCatalog(); });
  if (zh) await page.getByRole('button', { name: '打开侧边栏', exact: true }).click();
  await page.locator('button[data-session-id=A]').click();
  await page.getByRole('button', { name: zh ? '子智能体' : 'Subagents', exact: true }).click();
  await page.getByRole('treeitem', { name: /Research sources/ }).click();
  await expect(page).toHaveTitle('rustX startup ownership fixture');
  const child = page.locator('section[data-agent-id=child-0]');
  const input = child.getByRole('textbox');
  const stop = child.getByRole('button', { name: zh ? '停止' : 'Stop', exact: true });
  await expect(child.getByText('Retained source evidence.', { exact: true })).toBeAttached();
  await expect(child.getByRole('button', { name: zh ? '发送' : 'Send', exact: true })).toBeDisabled();
  await expect(stop).toBeEnabled();
  await expect(child.getByRole('button', { name: zh ? '模型与思考强度' : 'Model and thinking effort', exact: true })).toHaveCount(0);
  await expect(child.getByRole('button', { name: zh ? '工作区权限' : 'Workspace permissions', exact: true })).toBeDisabled();
  await input.fill('Keep my child draft');
  await expect(child.getByRole('button', { name: zh ? '插话' : 'Steer', exact: true })).toBeEnabled();
  const inputNode = await input.elementHandle();
  await expect.poll(() => page.evaluate(() => (window as any).startupFixture.requests().filter((r: any) => r.method === 'agent/observe').length)).toBe(2);
  await page.evaluate(() => (window as any).startupFixture.releaseChildObservation());
  const notice = child.locator('[data-child-observation-status]');
  await expect(notice).toBeVisible();
  await expect(child.locator('[data-composer-seat] [data-child-observation-status]')).toHaveCount(1);
  await expect(notice.locator('pre')).not.toBeVisible();
  await expect(child.getByText('Operation rejected', { exact: false })).not.toBeVisible();
  await expect(input).toHaveValue('Keep my child draft'); await expect(stop).toBeEnabled();
  await notice.locator('summary').click();
  await expect(notice.locator('pre')).toContainText('Connection reset by peer (os error 104)');
  await notice.locator('summary').click();
  await page.screenshot({ path: `/tmp/rustx-child-recovery-${theme}-${width}.png` });
  await notice.getByRole('button', { name: zh ? '子智能体状态暂时不可用，点击重试' : 'Child status unavailable. Click to retry' }).click();
  const connecting = notice.getByRole('button', { name: zh ? '正在重新连接子智能体…' : 'Reconnecting to child…' });
  await expect(connecting).toBeDisabled();
  await expect(child.getByText('Retained source evidence.', { exact: true })).toBeAttached();
  await expect(input).toHaveValue('Keep my child draft');
  expect(await inputNode!.evaluate(node => node.isConnected)).toBe(true);
  const reads = await page.evaluate(() => (window as any).startupFixture.requests().filter((r: any) => r.method === 'agent/observe'));
  expect(reads).toHaveLength(3); expect(reads[2].params).toMatchObject({ agent_id: 'child-0', after: null });
  await page.screenshot({ path: `/tmp/rustx-child-reconnecting-${theme}-${width}.png` });
  await page.evaluate(() => (window as any).startupFixture.releaseChildObservation());
  await expect(notice).toHaveCount(0);
  await expect(child.getByText('Recovered canonical source evidence.', { exact: true })).toBeVisible();
  await expect(input).toHaveValue('Keep my child draft'); await expect(stop).toBeEnabled();
  expect(await inputNode!.evaluate(node => node.isConnected)).toBe(true);
  await page.screenshot({ path: `/tmp/rustx-child-recovered-${theme}-${width}.png` });
  expect(await page.evaluate(() => (window as any).startupFixture.requests().filter((r: any) => ['agent/sendMessage', 'agent/interrupt', 'turn/start'].includes(r.method)))).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  expect(errors).toEqual([]);
});

import { test, expect } from '@playwright/test';

const fixture = `http://127.0.0.1:${process.env.RUSTX_E2E_FIXTURE_PORT ?? 5174}/test/fixtures/startup.html?existing&models&subagents&parent-messages`;
for (const theme of ['dark', 'light'] as const) for (const width of [1440, 390]) test(`DSH parent task/guidance bubbles in main and sidebar child ${theme} ${width}`, async ({ page, context }) => {
  const zh = width === 390, errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.setViewportSize({ width, height: 1000 });
  await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' });
  await page.addInitScript(locale => localStorage.setItem('rustx-locale-v1', locale), zh ? 'zh' : 'en');
  await page.goto(fixture);
  await page.waitForFunction(() => (window as any).startupFixture);
  await page.evaluate(() => { const f = (window as any).startupFixture; f.allow('session/summary'); f.allow('session/attach'); f.resumeCatalog(); });
  if (zh) await page.getByRole('button', { name: '打开侧边栏', exact: true }).click();
  await page.locator('button[data-session-id=A]').click();
  const rootInput = page.getByRole('textbox', { name: zh ? '消息' : 'Message', exact: true });
  await rootInput.fill('Keep parent draft');
  const agents = page.getByRole('button', { name: zh ? '子智能体' : 'Subagents', exact: true });
  await agents.click(); await page.getByRole('treeitem', { name: /Verify findings/ }).click();
  const child = page.locator('#conversation-view section[data-agent-id=child-1]');
  await expect(page).toHaveTitle('Session A — rustX');
  const task = child.locator('[data-chat-anchor-key="message:parent-task"]');
  const guidance = child.locator('[data-chat-anchor-key="message:parent-guidance"]');
  await expect(task.getByRole('article')).toContainText('任务：核对原始资料');
  await expect(guidance.getByRole('article')).toContainText('补充：保留原始链接');
  await expect(child.locator('[data-chat-flow-kind=user]')).toHaveCount(2);
  await expect(child.locator('[data-inbound-source]')).toHaveCount(0);
  await expect(task.locator('time')).toHaveAttribute('datetime', '2026-10-08T07:15:00Z');
  await expect(guidance.locator('time')).toHaveAttribute('datetime', '2026-10-08T07:16:00Z');
  await expect(child.getByRole('button', { name: zh ? '模型与思考强度' : 'Model and thinking effort', exact: true })).toHaveCount(0);
  const input = child.getByRole('textbox');
  await expect(input).toHaveAttribute('placeholder', zh ? '给此会话一个任务…' : 'Give this Session a task…');
  const article = task.getByRole('article'), stack = article.locator(':scope > div').first();
  const row = (await article.boundingBox())!, bubble = (await stack.boundingBox())!;
  expect(Math.abs(row.x + row.width - bubble.x - bubble.width)).toBeLessThanOrEqual(1);
  expect(bubble.width).toBeLessThanOrEqual(row.width * .83);
  expect(await stack.locator('div').first().evaluate(el => getComputedStyle(el).whiteSpace)).toBe('pre-wrap');
  const original = await stack.textContent();
  await task.hover(); await task.getByRole('button', { name: zh ? '复制' : 'Copy', exact: true }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(original);
  await input.fill('Keep child draft');
  await page.getByRole('tab', { name: zh ? '轨迹' : 'Trajectory', exact: true }).click();
  await expect(page.locator('[data-trajectory-scroll]:visible')).toBeVisible();
  await page.getByRole('tab', { name: zh ? '对话' : 'Chat', exact: true }).click();
  await expect(input).toHaveValue('Keep child draft');
  await expect(task.getByRole('article')).toBeAttached();
  await task.evaluate(el => { el.closest('[data-conversation-scroll]')!.scrollTop = 0; });
  await page.screenshot({ path: `/tmp/rustx-parent-bubbles-main-${theme}-${width}.png` });
  await page.getByRole('button', { name: 'Session A', exact: true }).click();
  await expect(rootInput).toHaveValue('Keep parent draft');
  await expect(page.locator('[data-inbound-source=agent]:visible')).toHaveCount(1);
  await agents.click();
  await page.getByRole('button', { name: zh ? '在侧栏打开 Verify findings' : 'Open Verify findings in sidebar', exact: true }).click();
  const aside = page.locator('[data-workbench] section[data-agent-id=child-1]');
  await expect(aside.locator('[data-chat-flow-kind=user]')).toHaveCount(2);
  await expect(aside.locator('[data-inbound-source]')).toHaveCount(0);
  await expect(aside.getByRole('button', { name: zh ? '模型与思考强度' : 'Model and thinking effort', exact: true })).toHaveCount(0);
  await aside.getByRole('article').first().evaluate(el => { el.closest('[data-conversation-scroll]')!.scrollTop = 0; });
  await page.screenshot({ path: `/tmp/rustx-parent-bubbles-aside-${theme}-${width}.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  expect(errors).toEqual([]);
});

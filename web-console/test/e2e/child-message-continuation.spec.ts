import { test, expect } from '@playwright/test';

const origin = `http://127.0.0.1:${process.env.RUSTX_E2E_FIXTURE_PORT ?? 5174}`;
for (const width of [1440, 390]) test(`resident Child Chat resumes unfinished message blocks after Trace at ${width}px`, async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.setViewportSize({ width, height: 1000 });
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
  await page.addInitScript(() => localStorage.setItem('rustx-locale-v1', 'en'));
  await page.goto(`${origin}/test/fixtures/startup.html?existing&models&subagents&child-message-continuation`);
  await page.evaluate(() => { const f = (window as any).startupFixture; f.allow('session/summary'); f.allow('session/attach'); f.resumeCatalog(); });
  if (width < 600) await page.getByRole('button', { name: 'Expand Sidebar', exact: true }).click();
  await page.locator('button[data-session-id=A]').click();
  await page.getByRole('button', { name: 'Subagents', exact: true }).click();
  await page.getByRole('treeitem', { name: /Verify findings/ }).click();
  const child = page.locator('section[data-agent-id=child-1]');
  const reads = () => page.evaluate(() => (window as any).startupFixture.requests().filter((request: any) => request.method === 'conversation/checkpointPage').length);
  await expect(child.locator('[data-message-file]')).toHaveCount(32);
  await expect.poll(reads).toBe(1);
  const input = child.getByRole('textbox');
  await input.fill('Keep the child draft');
  await page.getByRole('tab', { name: 'Trajectory', exact: true }).click();
  await expect(child).toHaveAttribute('data-view', 'trajectory');
  await page.evaluate(() => (window as any).startupFixture.release('conversation/checkpointPage'));
  await page.getByRole('tab', { name: 'Chat', exact: true }).click();
  await expect.poll(reads).toBe(2);
  await page.evaluate(() => (window as any).startupFixture.release('conversation/checkpointPage'));
  const body = child.getByText('Use all attached sources for the child task.', { exact: true });
  await expect(body).toBeVisible();
  await expect(input).toHaveValue('Keep the child draft');
  await expect(child.locator('[data-message-file]')).toHaveCount(32);
  await page.getByRole('tab', { name: 'Trajectory', exact: true }).click();
  await page.getByRole('tab', { name: 'Chat', exact: true }).click();
  await expect(body).toBeVisible();
  expect(await reads()).toBe(2);
  await expect(child.getByRole('alert')).toHaveCount(0);
  await page.screenshot({ path: `/tmp/rustx-child-continuation-${width}.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

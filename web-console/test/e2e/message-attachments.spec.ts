import { test, expect } from '@playwright/test';

const fixture = `http://127.0.0.1:${process.env.RUSTX_E2E_FIXTURE_PORT ?? 5174}/test/fixtures/startup.html?existing&models&subagents&message-attachments`;
for (const theme of ['dark', 'light'] as const) for (const width of [1440, 390]) test(`DSH message file tiles outside the text bubble ${theme} ${width}`, async ({ page, context }) => {
  const zh = width === 390, errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.setViewportSize({ width, height: 1000 });
  await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' });
  await page.addInitScript(locale => localStorage.setItem('rustx-locale-v1', locale), zh ? 'zh' : 'en');
  await page.goto(fixture);
  await page.waitForFunction(() => (window as any).startupFixture);
  await page.evaluate(() => { const f = (window as any).startupFixture; f.allow('session/summary'); f.allow('session/attach'); f.resumeCatalog(); });
  if (zh) await page.getByRole('button', { name: '打开侧边栏', exact: true }).click();
  await page.locator('button[data-session-id=A]').click();
  await expect(page).toHaveTitle('rustX startup ownership fixture');
  const compose = page.locator('[data-chat-anchor-key="message:compose"]:visible');
  const row = compose.locator('[data-message-attachments]'), card = row.locator('[data-message-file]'), body = compose.locator('[data-message-body]');
  await expect(card).toHaveText('compose.ymlYML');
  await expect(body).toHaveText('研究一下这个');
  await expect(body.locator('[data-message-file]')).toHaveCount(0);
  const tile = (await card.boundingBox())!, text = (await body.boundingBox())!;
  expect(tile.width).toBe(240); expect(tile.height).toBe(64);
  expect(Math.abs(tile.x + tile.width - text.x - text.width)).toBeLessThanOrEqual(1);
  expect(Math.abs(tile.y + tile.height + 8 - text.y)).toBeLessThanOrEqual(1);
  expect(await card.locator('svg').evaluate(el => el.getBoundingClientRect().width)).toBe(28);
  await expect(card).not.toContainText(/0B|undefined|NaN|文件附件|File attachment/);
  const only = page.locator('[data-chat-anchor-key="message:files-only"]:visible');
  await expect(only.locator('[data-message-file]')).toHaveCount(2);
  await expect(only.locator('[data-message-body]')).toHaveCount(0);
  const long = only.locator('[data-message-file]').first();
  await expect(long).toHaveAttribute('title', '架构说明-包含一个很长的文件名称以验证省略显示.pdf');
  await compose.hover(); await compose.getByRole('button', { name: zh ? '复制' : 'Copy', exact: true }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('研究一下这个');
  await compose.evaluate(el => { el.closest('[data-conversation-scroll]')!.scrollTop = 0; });
  await page.screenshot({ path: `/tmp/rustx-message-files-${theme}-${width}.png` });
  for (const element of await page.locator('[data-message-file]:visible').all()) {
    const bounds = (await element.boundingBox())!;
    expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.x + bounds.width).toBeLessThanOrEqual(width);
  }
  const input = page.getByRole('textbox', { name: zh ? '消息' : 'Message', exact: true });
  await input.fill('Retained root draft');
  await page.getByRole('button', { name: zh ? '子智能体' : 'Subagents', exact: true }).click();
  await page.getByRole('treeitem', { name: /Verify findings/ }).click();
  const child = page.locator('section[data-agent-id=child-1]');
  await expect(child.locator('[data-message-file]')).toHaveText('compose.ymlYML');
  await expect(child.locator('[data-message-body]')).toHaveText('研究一下这个');
  await expect(child.locator('[data-inbound-source]')).toHaveCount(0);
  await page.screenshot({ path: `/tmp/rustx-message-files-child-${theme}-${width}.png` });
  await page.getByRole('button', { name: 'Session A', exact: true }).click();
  await expect(input).toHaveValue('Retained root draft');
  await expect(card).toHaveText('compose.ymlYML');
  await page.getByRole('button', { name: zh ? '子智能体' : 'Subagents', exact: true }).click();
  await page.getByRole('button', { name: zh ? '在侧栏打开 Verify findings' : 'Open Verify findings in sidebar', exact: true }).click();
  const aside = page.locator('[data-workbench] section[data-agent-id=child-1]');
  await expect(aside.locator('[data-message-file]')).toHaveText('compose.ymlYML');
  await expect(aside.locator('[data-message-body]')).toHaveText('研究一下这个');
  await page.screenshot({ path: `/tmp/rustx-message-files-aside-${theme}-${width}.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  expect(errors).toEqual([]);
});

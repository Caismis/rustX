import { test, expect } from '@playwright/test';
const origin = `http://127.0.0.1:${process.env.RUSTX_E2E_FIXTURE_PORT ?? 5174}`;
for (const [width, locale] of [[1440, 'en'], [390, 'zh']] as const) test(`Agent Tool and Context replace activation activity (${width}, ${locale})`, async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.addInitScript(locale => localStorage.setItem('rustx-locale-v1', locale), locale);
  await page.setViewportSize({ width, height: 844 });
  await page.goto(`${origin}/test/fixtures/trajectory.html?agent-interactions`);
  await expect(page).toHaveTitle('Trajectory presentation contracts');
  if (width > 600) await page.evaluate(() => document.body.setAttribute('data-ds-dark-theme', ''));
  const ledger = page.getByRole('table', { name: locale === 'zh' ? '追踪明细' : 'Trace ledger', exact: true });
  const call = ledger.locator('[data-kind="tool"]');
  const report = ledger.locator('[data-kind="context"]');
  await expect(call).toContainText('subagent'); await expect(report).toContainText('parser review completed');
  await expect(ledger.locator('[data-kind="subagent"]')).toHaveCount(0);
  await expect(page.locator('[data-timeline-span="subagent"]')).toHaveCount(0);
  await expect(page.locator('[data-native-count]')).toHaveAttribute('data-native-count', '7');
  await expect(page.locator('[data-detail-reads]')).toHaveAttribute('data-detail-reads', '0');
  await page.screenshot({ path: `/tmp/rustx-agent-trajectory-${width}.png` });
  const search = page.getByRole('searchbox');
  await search.fill('Internal Agent activation audit'); await expect(call).toHaveCount(0); await expect(report).toHaveCount(0);
  await search.fill('subagent'); await expect(call).toBeVisible();
  await call.click();
  const inspector = page.getByRole('complementary', { name: locale === 'zh' ? '事件详情' : 'Event details', exact: true });
  await expect(inspector).toBeVisible(); await expect(inspector).not.toContainText(locale === 'zh' ? '子智能体' : 'SUBAGENT');
  await expect(inspector).toContainText('subagent');
  await inspector.getByRole('tab', { name: locale === 'zh' ? '结果' : 'Result', exact: true }).click();
  await expect(inspector.getByRole('tabpanel')).toContainText('parser-review');
  await expect(call).toHaveAttribute('aria-selected', 'true');
  await inspector.getByRole('button', { name: locale === 'zh' ? '关闭详情' : 'Close details', exact: true }).click();
  await expect(call).toBeFocused();
  await search.fill('parser review completed'); await expect(report).toBeVisible();
  await search.fill('');
  await page.getByRole('button', { name: 'Update', exact: true }).click();
  await expect(call).toBeVisible(); await expect(ledger.locator('[data-kind="subagent"]')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.locator('vite-error-overlay')).toHaveCount(0); expect(errors).toEqual([]);
});

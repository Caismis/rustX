/** Generate the locally bundled brand catalog from the exact pinned LobeHub package. */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { XMLParser } from 'fast-xml-parser';
const root = resolve(import.meta.dirname, '..');
const directory = resolve(root, 'node_modules/@lobehub/icons-static-svg/icons');
const files = new Set(readdirSync(directory));
const slugs = [...files].filter(file => /^[a-z0-9]+\.svg$/.test(file)).map(file => file.slice(0, -4)).sort();
const imports: string[] = [], rows: string[] = [];
const xml = new XMLParser();
for (const [index, slug] of slugs.entries()) {
  const color = files.has(`${slug}-color.svg`);
  const file = `${slug}${color ? '-color' : ''}.svg`;
  const svg = readFileSync(resolve(directory, file), 'utf8');
  const name = xml.parse(svg).svg?.title;
  if (typeof name !== 'string' || !name) throw new Error(`Missing brand title: ${file}`);
  imports.push(`import icon${index} from '@lobehub/icons-static-svg/icons/${file}?url&no-inline';`);
  rows.push(`  ${JSON.stringify(slug)}: { name: ${JSON.stringify(name)}, url: icon${index}, color: ${color} },`);
}
const output = '// Generated by scripts/provider-icons.ts from @lobehub/icons-static-svg 1.102.0 (MIT).\n'
  + imports.join('\n') + '\nexport const providerIcons: Record<string, { name: string; url: string; color: boolean }> = {\n'
  + rows.join('\n') + '\n};\n';
const path = resolve(root, 'src/app/settings/models/provider-icons.generated.ts');
if (process.argv.includes('--write')) writeFileSync(path, output);
else if (readFileSync(path, 'utf8') !== output) throw new Error('Provider icons drifted: run node scripts/provider-icons.ts --write');
console.log(`Verified ${slugs.length} locally bundled LobeHub brand icons`);

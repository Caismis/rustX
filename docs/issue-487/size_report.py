#!/usr/bin/env python3
"""Generate the Issue #487 size report (size-report.md) from three checkouts.

usage: size_report.py BASE_ROOT MAIN_ROOT HEAD_ROOT > size-report.md

BASE_ROOT is the starting base, MAIN_ROOT the latest main integrated into the
branch, HEAD_ROOT the final branch. Counting follows measure.py.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import measure  # noqa: E402

# (entry file, area paths)
HOTSPOTS = [
    ("src/durable/sqlite.rs", ["src/durable/sqlite.rs", "src/durable/sqlite"]),
    ("src/durable/inbox.rs", ["src/durable/inbox.rs", "src/durable/store.rs", "src/durable/store"]),
    ("src/runtime/conversation_runtime.rs", ["src/runtime/conversation_runtime.rs", "src/runtime/conversation_runtime"]),
    ("src/runtime_client/projection.rs", ["src/runtime_client/projection.rs", "src/runtime_client/projection"]),
    ("src/runtime_client/host.rs", ["src/runtime_client/host.rs", "src/runtime_client/host"]),
    ("src/agent/execution.rs", ["src/agent/execution.rs", "src/agent/execution"]),
    ("src/tools/mcp/mod.rs", ["src/tools/mcp"]),
    ("src/runtime/subagent/registry.rs", ["src/runtime/subagent/registry.rs", "src/runtime/subagent/registry"]),
    ("src/local_runtime/session.rs", ["src/local_runtime/session.rs", "src/local_runtime/session"]),
    ("src/local_runtime/composition.rs", ["src/local_runtime/composition.rs", "src/local_runtime/composition"]),
    ("src/local_runtime/session_runtime_manager.rs", ["src/local_runtime/session_runtime_manager.rs", "src/local_runtime/session_runtime_manager"]),
    ("src/local_runtime/configuration.rs", ["src/local_runtime/configuration.rs", "src/local_runtime/configuration"]),
    ("src/runtime/resources.rs", ["src/runtime/resources.rs", "src/runtime/adoption.rs"]),
    ("src/app_server/connection.rs", ["src/app_server/connection.rs", "src/app_server/connection", "src/app_server/rpc_error.rs"]),
    ("web-console/src/client/app-server.ts", ["web-console/src/client"]),
    ("tui/src/ui/app.ts", ["tui/src/ui"]),
    ("tui/src/app-server/session.ts", ["tui/src/app-server"]),
    ("tui/src/commands/dispatcher.ts", ["tui/src/commands"]),
    ("tui/src/ui/components/questionnaire.ts", ["tui/src/ui/components/questionnaire.ts", "tui/src/ui/components/questionnaire-answers.ts"]),
    ("tui/src/presentation/projection.ts", ["tui/src/presentation"]),
]
TEST_HOTSPOTS = [
    "tests/scripted/app_server/protocol.rs",
    "tests/scripted/app_server/configuration.rs",
    "tests/scripted/app_server/mod.rs",
]


def rows(root, paths):
    measure.ROOT = os.path.abspath(root)
    return measure.measure([p for p in paths if os.path.exists(os.path.join(root, p))])


def entry(root, path):
    r = rows(root, [path])
    return (r[0][0], r[0][1]) if r else None


def area(root, paths):
    r = rows(root, paths)
    prod = sum(x[0] for x in r)
    test = sum(x[1] for x in r)
    gen = sum(x[2] for x in r)
    largest = max(r, key=lambda x: x[0]) if r else (0, 0, 0, "-")
    return prod, test, gen, largest


def fmt(e):
    return "—" if e is None else f"{e[0]:,} / {e[1]:,}"


def main():
    base, main_root, head = sys.argv[1:4]
    out = []
    out.append("# Issue #487 size report\n")
    out.append("Generated by `docs/issue-487/size_report.py` with the counting method of")
    out.append("[`measure.py`](measure.py): physical lines including comments and blanks;")
    out.append("Rust `#[cfg(test)]` items and files reached only from test code (`mod`,")
    out.append("`#[path]`, `include!`) are test; TypeScript test/spec files are test and")
    out.append("`generated` paths/files are generated. Cells are `production / test`.\n")
    out.append("Columns: **base** is the starting base `6771928`; **main** is the latest")
    out.append("`origin/main` integrated into the branch, `7cf6b2da` (it adds PR #486 auxiliary")
    out.append("request ownership and PR #488, so area totals grow independently of this")
    out.append("refactor); **after** is the final branch head.")
    out.append("")
    out.append("## Entry files\n")
    out.append("| Entry file | base | main | after |")
    out.append("| --- | ---: | ---: | ---: |")
    for path, _ in HOTSPOTS:
        out.append(f"| `{path}` | {fmt(entry(base, path))} | {fmt(entry(main_root, path))} | {fmt(entry(head, path))} |")
    out.append("\n## Areas and largest production module\n")
    out.append("| Area (entry + its child modules) | main prod / test | after prod / test | largest production module after |")
    out.append("| --- | ---: | ---: | --- |")
    for path, paths in HOTSPOTS:
        m = area(main_root, paths)
        a = area(head, paths)
        largest = a[3]
        out.append(f"| `{path}` | {m[0]:,} / {m[1]:,} | {a[0]:,} / {a[1]:,} | `{largest[3]}` ({largest[0]:,}) |")
    out.append("\n## Test hotspots\n")
    out.append("| Test file | base | after | largest resulting test module |")
    out.append("| --- | ---: | ---: | --- |")
    for path in TEST_HOTSPOTS:
        b = entry(base, path)
        a = entry(head, path)
        directory = path[:-3] if not path.endswith("mod.rs") else None
        largest = "—"
        if directory and os.path.isdir(os.path.join(head, directory)):
            r = rows(head, [directory])
            if r:
                big = max(r, key=lambda x: x[1])
                largest = f"`{big[3]}` ({big[1]:,})"
        out.append(f"| `{path}` | {b[1]:,} | {a[1] if a else 0:,} | {largest} |")
    out.append("\n## Production modules above 2,000 lines after the refactor\n")
    measure.ROOT = os.path.abspath(head)
    big = [r for r in measure.measure(["src", "tui/src", "web-console/src", "protocol/app-server"]) if r[0] > 2000]
    if big:
        out.append("| Module | production |")
        out.append("| --- | ---: |")
        for r in sorted(big, key=lambda x: -x[0]):
            out.append(f"| `{r[3]}` | {r[0]:,} |")
    else:
        out.append("None.")
    print("\n".join(out))


if __name__ == "__main__":
    main()
